//! Stable errors preserve identity across context wrapping and presentation.
use serde::{Deserialize, Serialize};
use std::fmt;
macro_rules! codes {
    ($($variant:ident = $text:literal),* $(,)?) => {
        #[derive(Debug, Clone, PartialEq, Eq)]
        pub enum ErrorCode { $($variant,)* Adapter(String) }
        impl ErrorCode {
            pub fn as_str(&self) -> &str { match self { $(Self::$variant => $text,)* Self::Adapter(value)=>value } }
        }
        impl From<&str> for ErrorCode {
            fn from(value:&str)->Self {match value { $($text=>Self::$variant,)* other=>Self::Adapter(other.into()) }}
        }
    }
}
