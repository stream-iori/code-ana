#!/usr/bin/env python3
"""Generate compact physical tables and lossless logical projections.

The logical schema remains the reviewed Anatomist contract. Writer triggers
translate existing logical inserts/deletes; bulk node UPSERT is handled by the
storage promotion code so a replacement never cascades through live references.
"""
import pathlib
import re
import sqlite3
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'crates/storage/src/anatomist-schema.sql'
DESTINATION = ROOT / 'crates/storage/src/compact-schema.sql'
TABLES = ('nodes', 'edges', 'call_site_owners', 'call_sites', 'call_site_targets',
          'annotations', 'semantic_annotations', 'file_cache', 'file_dependencies',
          'symbol_dependencies', 'index_diagnostics', 'analysis_coverage')
REFS = {'edges': ('source_id', 'target_id'), 'call_site_owners': ('caller_id',),
        'call_site_targets': ('target_id',), 'annotations': ('node_id',),
        'semantic_annotations': ('node_id',)}
EXTERNAL = ('external_target_fqn', 'external_target_symbol',
            'external_target_language', 'external_target_provider_id')
META = {'nodes', 'edges', 'call_sites'}


def generate():
    original = SOURCE.read_text()
    connection = sqlite3.connect(':memory:')
    connection.executescript(original)
    statements = ["""-- Generated by scripts/generate-compact-schema.py; storage schema 7.
CREATE TABLE source_files(file_pk INTEGER PRIMARY KEY,path TEXT NOT NULL UNIQUE);
CREATE TABLE external_targets(external_pk INTEGER PRIMARY KEY,
 external_target_fqn TEXT,external_target_symbol TEXT,
 external_target_language TEXT,external_target_provider_id TEXT);
CREATE UNIQUE INDEX external_targets_identity ON external_targets(
 (external_target_fqn IS NULL),coalesce(external_target_fqn,''),
 (external_target_symbol IS NULL),coalesce(external_target_symbol,''),
 (external_target_language IS NULL),coalesce(external_target_language,''),
 (external_target_provider_id IS NULL),coalesce(external_target_provider_id,''));
CREATE INDEX external_targets_fqn ON external_targets(external_target_fqn);
CREATE TABLE metadata_values(value_pk INTEGER PRIMARY KEY,digest BLOB NOT NULL
 CHECK(length(digest)=32),value TEXT NOT NULL);
CREATE INDEX metadata_values_digest ON metadata_values(digest);
"""]
    specs = {}
    for table in TABLES:
        info = list(connection.execute('PRAGMA table_info(' + table + ')'))
        columns = [r[1] for r in info]
        ddl = connection.execute('SELECT sql FROM sqlite_schema WHERE name=?', (table,)).fetchone()[0]
        ddl = ddl.replace('CREATE TABLE ' + table, 'CREATE TABLE graph_' + table, 1)
        for column in REFS.get(table, ()):
            ddl = re.sub(r'\b' + column + r' TEXT', column + ' INTEGER', ddl)
        ddl = ddl.replace('REFERENCES nodes(id)', 'REFERENCES graph_nodes(node_pk)')
        ddl = ddl.replace('REFERENCES call_site_owners(owner_pk)', 'REFERENCES graph_call_site_owners(owner_pk)')
        ddl = ddl.replace('REFERENCES call_sites(site_pk)', 'REFERENCES graph_call_sites(site_pk)')
        files = [c for c in columns if c in ('source_file', 'depends_on_file')]
        for column in files:
            ddl = re.sub(r'\b' + column + r' TEXT', column + ' INTEGER', ddl)
        if table == 'nodes':
            ddl = ddl.replace('id TEXT PRIMARY KEY,', 'node_pk INTEGER PRIMARY KEY,\n    id TEXT NOT NULL UNIQUE,')
        external = 'external_target_fqn' in columns
        if external:
            for column in EXTERNAL:
                ddl = re.sub(r'\s*' + column + r' TEXT,', '', ddl)
            ddl = ddl.replace('external_target_fqn IS NULL', '1=1')
            ddl = ddl.replace('external_target_fqn IS NOT NULL', 'external_pk IS NOT NULL')
            pos = ddl.index('(') + 1
            ddl = ddl[:pos] + 'external_pk INTEGER REFERENCES external_targets(external_pk),' + ddl[pos:]
        if table in META:
            pos = ddl.index('(') + 1
            ddl = ddl[:pos] + 'metadata_pk INTEGER REFERENCES metadata_values(value_pk),' + ddl[pos:]
            ddl = ddl[:-1] + ',CHECK(metadata IS NULL OR metadata_pk IS NULL)\n)'
        for column in files:
            pos = ddl.rfind(')')
            ddl = ddl[:pos] + ',FOREIGN KEY(' + column + ') REFERENCES source_files(file_pk)\n' + ddl[pos:]
        statements.append(ddl + ';')
        projections = []
        joins = []
        for column in files:
            joins.append('LEFT JOIN source_files f_' + column + ' ON f_' + column + '.file_pk=t.' + column)
        for column in REFS.get(table, ()):
            joins.append('LEFT JOIN graph_nodes n_' + column + ' ON n_' + column + '.node_pk=t.' + column)
        if external:
            joins.append('LEFT JOIN external_targets x ON x.external_pk=t.external_pk')
        if table in META:
            joins.append('LEFT JOIN metadata_values m ON m.value_pk=t.metadata_pk')
        for column in columns:
            if column in files:
                value = 'f_' + column + '.path'
            elif column in REFS.get(table, ()):
                value = 'n_' + column + '.id'
            elif external and column in EXTERNAL:
                value = 'x.' + column
            elif table in META and column == 'metadata':
                value = 'coalesce(t.metadata,m.value)'
            else:
                value = 't.' + column
            projections.append(value + ' AS ' + column)
        statements.append('CREATE VIEW ' + table + ' AS SELECT ' + ','.join(projections)
                          + ' FROM graph_' + table + ' t ' + ' '.join(joins) + ';')
        before = []
        for column in files:
            before.append('INSERT OR IGNORE INTO source_files(path) SELECT NEW.' + column + ' WHERE NEW.' + column + ' IS NOT NULL AND NOT EXISTS(SELECT 1 FROM source_files WHERE path=NEW.' + column + ');')
        external_lookup = ''
        if external:
            identity = ' AND '.join('(' + c + ' IS NULL)=(NEW.' + c + ' IS NULL) AND coalesce(' + c + ",'')=coalesce(NEW." + c + ",'')" for c in EXTERNAL)
            present = ' OR '.join('NEW.' + c + ' IS NOT NULL' for c in EXTERNAL)
            before.append('INSERT OR IGNORE INTO external_targets(' + ','.join(EXTERNAL) + ') SELECT '
                          + ','.join('NEW.' + c for c in EXTERNAL) + ' WHERE ' + present + ';')
            external_lookup = '(SELECT external_pk FROM external_targets WHERE ' + identity + ')'
            if table == 'edges':
                before.append("SELECT CASE WHEN NOT ((coalesce(NEW.is_external,0)=0 AND NEW.target_id IS NOT NULL AND NEW.external_target_fqn IS NULL) OR (NEW.is_external=1 AND NEW.target_id IS NULL AND NEW.external_target_fqn IS NOT NULL)) THEN RAISE(ABORT,'GRAPH_TARGET_SHAPE') END;")
            else:
                before.append("SELECT CASE WHEN (NEW.target_id IS NOT NULL)=(NEW.external_target_fqn IS NOT NULL) THEN RAISE(ABORT,'GRAPH_TARGET_SHAPE') END;")
        physical_columns = [c for c in columns if not (external and c in EXTERNAL)]
        if external:
            physical_columns.append('external_pk')
        values = []
        defaults = {r[1]: r[4] for r in info}
        for column in physical_columns:
            if column in files:
                value = '(SELECT file_pk FROM source_files WHERE path=NEW.' + column + ')'
            elif column in REFS.get(table, ()):
                value = '(SELECT node_pk FROM graph_nodes WHERE id=NEW.' + column + ')'
            elif column == 'external_pk':
                value = external_lookup
            else:
                value = 'NEW.' + column
                if defaults.get(column) is not None:
                    value = 'coalesce(' + value + ',' + defaults[column] + ')'
            values.append(value)
        insertion = 'INSERT INTO graph_' + table + '(' + ','.join(physical_columns) + ') VALUES(' + ','.join(values) + ')'
        if table == 'nodes':
            updates = ','.join(c + '=excluded.' + c for c in physical_columns if c != 'id')
            insertion += ' ON CONFLICT(id) DO UPDATE SET ' + updates + ' WHERE graph_nodes.fact_hash IS NOT excluded.fact_hash'
        elif table in ('file_cache', 'analysis_coverage'):
            keys = [r[1] for r in info if r[5]]
            updates = ','.join(c + '=excluded.' + c for c in physical_columns if c not in keys)
            insertion += ' ON CONFLICT(' + ','.join(keys) + ') DO UPDATE SET ' + updates
        statements.append('CREATE TRIGGER compact_' + table + '_insert INSTEAD OF INSERT ON ' + table
                          + ' BEGIN ' + ' '.join(before) + ' ' + insertion + '; END;')
        primary = [r[1] for r in info if r[5]]
        if not primary:
            # Targets intentionally retain duplicate observations. The logical
            # row's complete identity suffices for current whole-site deletion.
            primary = columns
        condition = ' AND '.join(c + ' IS OLD.' + c for c in primary)
        if table == 'call_site_targets':
            condition = 'call_site_pk=OLD.call_site_pk'
        else:
            for column in files:
                condition = condition.replace(column + ' IS OLD.' + column, column + ' IS (SELECT file_pk FROM source_files WHERE path=OLD.' + column + ')')
        statements.append('CREATE TRIGGER compact_' + table + '_delete INSTEAD OF DELETE ON ' + table
                          + ' BEGIN DELETE FROM graph_' + table + ' WHERE ' + condition + '; END;')
        specs[table] = (files, external)
    for name, table, ddl in connection.execute("SELECT name,tbl_name,sql FROM sqlite_schema WHERE type='index' AND sql IS NOT NULL"):
        if table not in TABLES:
            continue
        ddl = ddl.replace(' ON ' + table + '(', ' ON graph_' + table + '(')
        ddl = ddl.replace(' ON ' + table + ' (', ' ON graph_' + table + ' (')
        if specs[table][1]:
            ddl = ddl.replace('external_target_fqn', 'external_pk')
        # Do not index the NULL half of internal/external target space.
        if name in ('idx_edges_external_target_fqn', 'idx_edges_relation_external_fqn'):
            ddl += ' WHERE external_pk IS NOT NULL AND is_external=1'
        elif name in ('idx_edges_target_relation', 'idx_edges_relation_external_target'):
            ddl += ' WHERE target_id IS NOT NULL'
        statements.append(ddl + ';')
    # Small non-interned control tables keep the upstream layout.
    for table in ('project_meta', 'index_providers'):
        statements.append(connection.execute('SELECT sql FROM sqlite_schema WHERE name=?', (table,)).fetchone()[0] + ';')
    statements.append("""CREATE VIRTUAL TABLE node_names USING fts5(qualified_name,label,content='graph_nodes',content_rowid='node_pk');
CREATE TRIGGER nodes_ai AFTER INSERT ON graph_nodes BEGIN INSERT INTO node_names(rowid,qualified_name,label) VALUES(new.node_pk,new.qualified_name,new.label); END;
CREATE TRIGGER nodes_ad AFTER DELETE ON graph_nodes BEGIN INSERT INTO node_names(node_names,rowid,qualified_name,label) VALUES('delete',old.node_pk,old.qualified_name,old.label); END;
CREATE TRIGGER nodes_au AFTER UPDATE OF qualified_name,label ON graph_nodes
WHEN old.qualified_name IS NOT new.qualified_name OR old.label IS NOT new.label BEGIN
 INSERT INTO node_names(node_names,rowid,qualified_name,label) VALUES('delete',old.node_pk,old.qualified_name,old.label);
 INSERT INTO node_names(rowid,qualified_name,label) VALUES(new.node_pk,new.qualified_name,new.label); END;
""")
    statements.append((ROOT / 'crates/storage/src/compact-meta.sql').read_text())
    connection.close()
    return '\n\n'.join(statements) + '\n'


if __name__ == '__main__':
    text = generate()
    if '--check' in sys.argv:
        assert DESTINATION.read_text() == text, 'COMPACT_SCHEMA_DRIFT'
    else:
        DESTINATION.write_text(text)
